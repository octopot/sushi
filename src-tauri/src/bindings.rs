//! The TypeScript side of what the commands send: src/bindings/ is generated from the Rust types,
//! and `Replies.ts` there names the reply of every command, taken from its signature. src/ipc.ts
//! builds its command map on them. A changed field, struct or command reply fails this test until
//! `make bindings` writes the files again, and then `npm run build` fails at every place on the page
//! (and in the site's demo stub) that still reads the old shape.
use std::{collections::BTreeSet, env, fs, path::PathBuf};
use ts_rs::{Config, TS};

use crate::{
    library::{Entry, Kind},
    rewrite::Edit,
    settings::{Rule, Settings, Term},
};

/// What the page receives from a command's return type: the `Ok` value of a `Result`, else the value.
trait Reply {
    type Value: TS + 'static;
}
impl<T: TS + 'static> Reply for Result<T, String> {
    type Value = T;
}
impl Reply for Option<String> {
    type Value = Option<String>;
}

macro_rules! hole {
    ($u:tt) => {
        todo!()
    };
}

/// One line per command: its path, one `_` per parameter, `.await` when it is async, and its return
/// type. The closure is never called; it only makes the compiler check the line against the function.
macro_rules! replies {
    ($($($path:ident)::+ ($($u:tt)*) $(. $aw:tt)? -> $ret:ty;)*) => {
        #[allow(unreachable_code, unused_variables, clippy::diverging_sub_expression, clippy::let_underscore_future)]
        fn signatures() {
            $(let _ = async { let _: $ret = crate::$($path)::+($(hole!($u)),*) $(. $aw)?; };)*
        }
        fn replies(cfg: &Config) -> Vec<(&'static str, String)> {
            // The command's name is the function's: the last segment of its path.
            vec![$((stringify!($($path)::+).rsplit(':').next().unwrap().trim(), <<$ret as Reply>::Value as TS>::name(cfg)),)*]
        }
    };
}

replies! {
    hide_launcher(_) -> Result<(), String>;
    copy_text(_) -> Result<(), String>;
    startup_notes(_) -> Option<String>;
    settings::settings_load(_).await -> Result<Settings, String>;
    settings::dictionary_open(_).await -> Result<(), String>;
    library::library_list(_ _).await -> Result<Vec<Entry>, String>;
    library::library_read(_ _ _).await -> Result<String, String>;
    rewrite::rewrite(_ _ _ _ _ _).await -> Result<Edit, String>;
    rewrite::cancel_rewrite(_ _) -> Result<(), String>;
    rewrite::warm_model(_).await -> Option<String>;
    rewrite::ollama_download().await -> Result<(), String>;
}

const NOTE: &str = "// Generated by src-tauri/src/bindings.rs from the commands' return types: run `make bindings`.\n";

/// `Replies.ts`: imports every generated type, so any reply may name one.
fn render_replies(cfg: &Config, types: &BTreeSet<String>) -> String {
    let imports: String = types
        .iter()
        .map(|ty| format!("import type {{ {ty} }} from './{ty}'\n"))
        .collect();
    let lines: String = replies(cfg)
        .into_iter()
        .map(|(name, ty)| format!("  {name}: {ty}\n"))
        .collect();
    format!("{NOTE}{imports}\nexport interface Replies {{\n{lines}}}\n")
}

/// The commands `generate_handler!` registers in main.rs, by their last path segment.
fn registered() -> BTreeSet<String> {
    let main = include_str!("main.rs");
    let list = main
        .split_once("generate_handler![")
        .and_then(|(_, rest)| rest.split_once(']'))
        .expect("main.rs registers its commands with generate_handler!")
        .0;
    list.split(',')
        .map(|path| path.trim().rsplit("::").next().unwrap().to_string())
        .filter(|name| !name.is_empty())
        .collect()
}

struct Files {
    dir: PathBuf,
    write: bool,
    seen: BTreeSet<String>,
    types: BTreeSet<String>,
    stale: Vec<String>,
}

impl Files {
    fn check(&mut self, file: &str, fresh: &str) {
        self.seen.insert(file.into());
        let path = self.dir.join(file);
        if self.write {
            fs::create_dir_all(&self.dir).unwrap();
            fs::write(&path, fresh).unwrap();
        } else if fs::read_to_string(&path).ok().as_deref() != Some(fresh) {
            self.stale
                .push(format!("src/bindings/{file} is out of date"));
        }
    }
    fn ty<T: TS + 'static>(&mut self, cfg: &Config) {
        self.types.insert(T::ident(cfg));
        let file = T::output_path().expect("an exportable type");
        let fresh = T::export_to_string(cfg).expect("bindings render");
        self.check(&file.to_string_lossy(), &fresh);
    }
}

#[test]
fn typescript_bindings_are_current() {
    let _ = signatures;
    let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../src/bindings");
    // Timestamps in milliseconds fit a JavaScript number; bigint would not survive JSON.
    let cfg = Config::new().with_out_dir(&dir).with_large_int("number");
    let write = env::var_os("SUSHI_WRITE_BINDINGS").is_some();
    if write {
        let _ = fs::remove_dir_all(&dir);
    }
    let mut files = Files {
        dir,
        write,
        seen: BTreeSet::new(),
        types: BTreeSet::new(),
        stale: Vec::new(),
    };
    files.ty::<Edit>(&cfg);
    files.ty::<Entry>(&cfg);
    files.ty::<Kind>(&cfg);
    files.ty::<Settings>(&cfg);
    files.ty::<Rule>(&cfg);
    files.ty::<Term>(&cfg);
    let replies_ts = render_replies(&cfg, &files.types);
    files.check("Replies.ts", &replies_ts);

    let mut problems = files.stale;
    for entry in fs::read_dir(&files.dir).into_iter().flatten().flatten() {
        let name = entry.file_name().to_string_lossy().into_owned();
        if !files.seen.contains(&name) {
            problems.push(format!("src/bindings/{name} is no longer generated"));
        }
    }
    let listed: BTreeSet<String> = replies(&cfg)
        .into_iter()
        .map(|(name, _)| name.to_string())
        .collect();
    if listed != registered() {
        problems.push(format!(
            "replies! in bindings.rs lists {listed:?}, main.rs registers {:?}",
            registered()
        ));
    }
    assert!(
        problems.is_empty(),
        "run `make bindings`: {}",
        problems.join("; ")
    );
}
